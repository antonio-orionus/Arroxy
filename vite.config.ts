// `unplugin-icons` virtual modules (`~icons/simple-icons/x`,
// `~icons/logos/facebook`, etc.) are generated by the Vite plugin at build
// time. Vitest doesn't run that plugin — without a regex alias, every test
// that transitively imports ShareDialog crashes on import resolution. Map
// every `~icons/*` to a single inert SVG stub.
// Workspace packages resolve to their sources, subpath exports included
// (`yt-dlp-bridge/runner` → `src/runner.ts`), so tests never need a build.
const workspaceAlias = [
	{find: /^yt-dlp-bridge\/(.+)$/, replacement: `${path.resolve('packages/yt-dlp-bridge/src')}/$1.ts`},
	{find: /^yt-dlp-bridge$/, replacement: path.resolve('packages/yt-dlp-bridge/src/index.ts')}
]

const testAlias = [...workspaceAlias, ...Object.entries(testAliasObj).map(([find, replacement]) => ({find, replacement})), {find: /^~icons\/.*/, replacement: path.resolve('tests/__mocks__/icons-stub.tsx')}]

// Vitest defaults to 5s, which is not enough headroom on the Windows CI runner.
// A good number of the node tests do real filesystem work in `os.tmpdir()` —
// mkdtemp, write, then hash the bytes back — and on Windows every one of those
// touches goes through the virus scanner before it returns. Locally those tests
// finish in milliseconds; on a contended runner one of them occasionally walks
// past 5s and fails as a timeout with nothing actually wrong. 20s still catches
// a genuinely hung test quickly enough to be useful.
const TEST_TIMEOUT_MS = 20_000

// Tests that need every locale fully translated. A PR changes English only, so they run in the
// release completeness gate (`bun run check:i18n:complete`), not in `bun run test` (ADR 0017).
const I18N_COMPLETE_TESTS = 'tests/i18n-complete/**'

// Every gate `bun run check` runs in parallel. `quality-gate` runs packages:check
// only after all of them pass, because the package gates rebuild shared outputs.
const QUALITY_GATES = ['check:static', 'check:shell', 'check:tooling-parity', 'check:tooling-contract', 'knip', 'check:loc', 'check:selection-parity', 'check:filename-parity', 'check:pins', 'check:i18n', 'check:donation-addresses', 'check:changelog', 'test']
// CI runs the unit tests in shards on their own runners (`ci.yml`), so its gates
// job sets CHECK_TESTS_SEPARATELY and the gate leaves them out; locally they run.
const CHECK_GATES = process.env.CHECK_TESTS_SEPARATELY === '1' ? QUALITY_GATES.filter(gate => gate !== 'test') : QUALITY_GATES

// Format, then lint with type checks (typeCheck is on). This is `vp check`
// plus --deny-warnings, which `vp check` cannot take. Type-aware rules resolve
// ytdlp-errors through its built types, so build it first. README sources are
// skipped: readme-src is rebuilt by its own rule.
