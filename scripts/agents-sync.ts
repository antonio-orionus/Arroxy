// Regenerates per-tool agent adapters from the shared `.agents/` sources.
// `.agents/skills/` and `.agents/mcp.json` are the only tracked inputs; every
// output here is gitignored local state, safe to delete and rebuild. The one
// untracked input is the maintainer's personal `.internal/AGENTS.md`, wired into
// each tool when it exists so it loads as automatically as `AGENTS.md`.
import {lstat, mkdir, readdir, readFile, readlink, rm, stat, symlink, writeFile} from 'node:fs/promises'
import path from 'node:path'
import {fileURLToPath} from 'node:url'
import {z} from 'zod'

const mcpServerSchema = z.strictObject({command: z.string().min(1), args: z.array(z.string()).default([])})
const agentsMcpConfigSchema = z.strictObject({servers: z.record(z.string().min(1), mcpServerSchema)})

export type AgentsMcpConfig = z.infer<typeof agentsMcpConfigSchema>

// Claude Code is the only supported tool that does not read `.agents/skills` natively
// (Codex and OpenCode both do), so it is the only skill adapter.
const CLAUDE_SKILLS_DIR = '.claude/skills'

const PERSONAL_INSTRUCTIONS = '.internal/AGENTS.md'
// Claude Code loads this from the project root; an `@` import through `.internal`
// would resolve outside the repo and need a per-project approval instead.
const CLAUDE_LOCAL = 'CLAUDE.local.md'

export function parseAgentsMcpConfig(value: unknown): AgentsMcpConfig {
	return agentsMcpConfigSchema.parse(value)
}

// JSON string literals are valid TOML basic strings: every JSON escape is also a TOML escape.
const tomlString = (value: string): string => JSON.stringify(value)

function renderCodexToml(config: AgentsMcpConfig): string {
	return Object.entries(config.servers)
		.map(([name, server]) => `[mcp_servers.${tomlString(name)}]\ncommand = ${tomlString(server.command)}\nargs = [${server.args.map(tomlString).join(', ')}]\n`)
		.join('\n')
}

const json = (value: unknown): string => `${JSON.stringify(value, null, '\t')}\n`

// Codex has no way to include another instruction file, so it gets a copy of the
// personal instructions; OpenCode reads the file itself through `instructions`.
export function renderMcpTargets(config: AgentsMcpConfig, personalInstructions?: string): Record<'.mcp.json' | '.codex/config.toml' | 'opencode.jsonc', string> {
	const servers = Object.entries(config.servers)
	// A TOML key after a table header belongs to that table, so this precedes the servers.
	const codexInstructions = personalInstructions === undefined ? '' : `developer_instructions = ${tomlString(personalInstructions)}\n\n`
	return {
		'.mcp.json': json({mcpServers: Object.fromEntries(servers.map(([name, s]) => [name, {type: 'stdio', command: s.command, args: s.args}]))}),
		'.codex/config.toml': `# Generated by \`bun run agents:sync\` from .agents/mcp.json and ${PERSONAL_INSTRUCTIONS} — do not edit.\n${codexInstructions}${renderCodexToml(config)}`,
		'opencode.jsonc': json({$schema: 'https://opencode.ai/config.json', ...(personalInstructions === undefined ? {} : {instructions: [PERSONAL_INSTRUCTIONS]}), mcp: Object.fromEntries(servers.map(([name, s]) => [name, {type: 'local', command: [s.command, ...s.args], enabled: true}]))})
	}
}

async function exists(target: string): Promise<boolean> {
	return stat(target).then(
		() => true,
		() => false
	)
}

async function listSharedSkills(repoRoot: string): Promise<string[]> {
	const dir = path.join(repoRoot, '.agents/skills')
	if (!(await exists(dir))) return []
	const entries = await readdir(dir, {withFileTypes: true})
	const names = await Promise.all(entries.map(async entry => ((entry.isDirectory() || entry.isSymbolicLink()) && (await exists(path.join(dir, entry.name, 'SKILL.md'))) ? entry.name : null)))
	return names.filter((name): name is string => name !== null).sort()
}

async function syncClaudeSkillLinks(repoRoot: string): Promise<void> {
	const linkDir = path.join(repoRoot, CLAUDE_SKILLS_DIR)
	await mkdir(linkDir, {recursive: true})

	for (const entry of await readdir(linkDir, {withFileTypes: true})) {
		const link = path.join(linkDir, entry.name)
		if (entry.isSymbolicLink() && !(await exists(link))) await rm(link)
	}

	for (const name of await listSharedSkills(repoRoot)) {
		const link = path.join(linkDir, name)
		const current = await lstat(link).catch(() => null)
		if (current && !current.isSymbolicLink()) {
			console.warn(`agents:sync: leaving ${CLAUDE_SKILLS_DIR}/${name} alone — it is not a link`)
			continue
		}
		if (current) await rm(link)
		// Junctions need no Windows symlink privilege but require an absolute target.
		if (process.platform === 'win32') await symlink(path.join(repoRoot, '.agents/skills', name), link, 'junction')
		else await symlink(path.join('../../.agents/skills', name), link)
	}
}

// Only a missing file means "nothing to wire"; any other failure would silently drop the rules.
async function readPersonalInstructions(repoRoot: string): Promise<string | undefined> {
	return readFile(path.join(repoRoot, PERSONAL_INSTRUCTIONS), 'utf8').catch((error: unknown) => {
		const code = error instanceof Error && 'code' in error ? error.code : undefined
		if (code === 'ENOENT' || code === 'ENOTDIR') return undefined
		throw error
	})
}

async function syncClaudeLocalLink(repoRoot: string, hasPersonalInstructions: boolean): Promise<void> {
	const link = path.join(repoRoot, CLAUDE_LOCAL)
	const current = await lstat(link).catch(() => null)
	// Windows stores the target with backslashes, so compare normalized paths.
	const ours = current?.isSymbolicLink() === true && path.normalize(await readlink(link)) === path.normalize(PERSONAL_INSTRUCTIONS)
	if (current && !ours) {
		if (hasPersonalInstructions) console.warn(`agents:sync: leaving ${CLAUDE_LOCAL} alone — it is not this sync's link, so Claude Code does not load ${PERSONAL_INSTRUCTIONS}`)
		return
	}
	if (!hasPersonalInstructions) {
		if (ours) await rm(link)
		return
	}
	if (ours) return
	// A file symlink needs Developer Mode on Windows; without it Claude Code just goes without.
	await symlink(PERSONAL_INSTRUCTIONS, link, 'file').catch((error: unknown) => console.warn(`agents:sync: could not link ${CLAUDE_LOCAL} to ${PERSONAL_INSTRUCTIONS}: ${String(error)}`))
}

async function writeMcpTargets(repoRoot: string, personalInstructions: string | undefined): Promise<void> {
	const source = path.join(repoRoot, '.agents/mcp.json')
	if (!(await exists(source))) return
	const config = parseAgentsMcpConfig(JSON.parse(await readFile(source, 'utf8')))
	for (const [target, content] of Object.entries(renderMcpTargets(config, personalInstructions))) {
		await mkdir(path.dirname(path.join(repoRoot, target)), {recursive: true})
		await writeFile(path.join(repoRoot, target), content)
	}
}

// The part of the sync that depends on `.internal/AGENTS.md`, for refreshing other worktrees.
export async function syncPersonalInstructions(repoRoot: string): Promise<void> {
	const personalInstructions = await readPersonalInstructions(repoRoot)
	await syncClaudeLocalLink(repoRoot, personalInstructions !== undefined)
	await writeMcpTargets(repoRoot, personalInstructions)
}

export async function syncAgents(repoRoot: string): Promise<void> {
	await syncClaudeSkillLinks(repoRoot)
	await syncPersonalInstructions(repoRoot)
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
	await syncAgents(process.cwd())
	console.log('agents:sync complete')
}
